/* ---------------- Seçili dil + t() yardımcıları ---------------- */

/* Varsayılan dil İngilizce (global ürün); kullanıcı Kurulum'da veya Ayarlar'dan değiştirir */
const I18N_LANG = (() => {
  const l = localStorage.getItem('uiLang') || 'en';
  return I18N[l] ? l : 'en';
})();

/* t(anahtar, {param: değer}) — seçili dil → en → tr sırasıyla arar */
function t(key, params) {
  let s = I18N[I18N_LANG][key];
  if (s === undefined) s = I18N.en[key];
  if (s === undefined) s = I18N.tr[key];
  if (s === undefined) return key;
  if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (params[k] !== undefined ? String(params[k]) : m));
  return s;
}

/* Sayı biçimlendirme için yerel ayar (toLocaleString) */
const I18N_LOCALE = ({ tr: 'tr-TR', en: 'en-US', es: 'es-ES', zh: 'zh-CN', ar: 'ar-SA', hi: 'hi-IN', pt: 'pt-BR', fr: 'fr-FR', ru: 'ru-RU', de: 'de-DE' })[I18N_LANG] || 'tr-TR';

/* Belge dili ve yönü (Arapça → RTL) */
document.documentElement.lang = I18N_LANG;
document.documentElement.dir = I18N_LANG === 'ar' ? 'rtl' : 'ltr';

/* index.html'deki statik metinleri çevirir:
   data-i18n → textContent, data-i18n-title → title, data-i18n-ph → placeholder */
function applyI18nDom(root = document) {
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.getAttribute('data-i18n')); });
  root.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.getAttribute('data-i18n-title')); });
  root.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.getAttribute('data-i18n-ph')); });
}

/* Script gövde sonunda yüklendiği için DOM hazırdır */
applyI18nDom(document);
